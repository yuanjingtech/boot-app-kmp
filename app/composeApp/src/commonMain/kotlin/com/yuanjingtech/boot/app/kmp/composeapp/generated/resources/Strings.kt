import androidx.compose.runtime.Composable
import org.jetbrains.compose.resources.stringResource

/**
 * Public string resource accessors.
 * These are re-exports of the internal [Res] string resources.
 */
object Strings {
    @Composable
    fun appName(): String = stringResource(Res.string.app_name)

    @Composable
    fun tabItemMain(): String = stringResource(Res.string.tab_item_main)

    @Composable
    fun tabItemSetting(): String = stringResource(Res.string.tab_item_setting)
}
